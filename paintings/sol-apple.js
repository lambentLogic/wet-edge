// An imagined apple: afternoon light, pale linen, lost edges in the shade.
const S = window.__sim, h = S.headless, V = S.values, M = window.__minds;
window.__paintLog = [];
const log = t => { window.__paintLog.push(t); console.log('[paint]', t); };
const curve = (f,n=28) => Array.from({length:n+1},(_,i)=>f(i/n));
const apple = curve(t => { const a=t*Math.PI*2; return [465+169*Math.cos(a)*(1+0.05*Math.sin(3*a)), 397+162*Math.sin(a)+16*Math.cos(2*a)]; },72);
const oval = (x,y,rx,ry) => curve(t=>[x+rx*Math.cos(t*2*Math.PI),y+ry*Math.sin(t*2*Math.PI)],48);
const load = (mix,p,r,w=0.3) => { S.tool('paint'); h.setBrushPreset('round'); h.setBrush(mix); V.brushPigment=p; V.brushRadius=r; V.dipLoad=w; };
window.__paintDone = (async()=>{
  const dry = async () => { S.act('dry',true); try { await S.skipTo('dry'); } finally { S.act('dry',false); } };
  h.setPaper('coldPress',37); h.setTone('natural'); S.clear();
  log('a loose warm wash behind the apple');
  h.setBrushPreset('mop'); h.setBrush([['Transparent Yellow Oxide',3],['Quinacridone Rose',1]]); V.brushRadius=65; V.brushPigment=0.045;
  await S.wash([[100,105],[872,98],[906,450],[95,448]],{kind:'graded',fadeTo:0.12,paper:'moist'});
  await dry();
  log('cool cast shadow on the linen');
  await S.dampen(M.maskOf(oval(600,553,237,62)),0.8,0.012,18);
  load([['French Ultramarine',3],['Transparent Red Oxide',1]],0.12,27,0.15);
  for (const [y,x0,x1] of [[544,431,746],[558,454,777],[574,506,714]]) await S.path(curve(t=>[x0+(x1-x0)*t,y+6*Math.sin(t*3),0.15+0.65*Math.sin(Math.PI*t)],16),2);
  await dry();
  log('the whole red form, keeping the light warm');
  h.setBrushPreset('mop'); h.setBrush([['Pyrrole Rubine',4],['Transparent Yellow Oxide',1]]); V.brushRadius=35; V.brushPigment=0.24; V.dipLoad=0.7;
  await S.wash(apple,{kind:'variegated',into:[['Pyrrole Rubine',3],['Perylene Violet',1]],direction:'across',paper:'moist'});
  await S.look('red-form');
  log('curved shadow strokes while the apple is satin');
  await S.skipTo('satin',{points:[[500,430]]});
  load([['Pyrrole Rubine',2],['Perylene Violet',1],['French Ultramarine',0.4]],0.25,26,0.08);
  for(let k=0;k<4;k++) await S.path(curve(t=>[542+17*k+26*Math.sin(t*Math.PI),300+225*t,0.15+0.7*Math.sin(t*Math.PI)],22),2);
  await S.path(curve(t=>[343+237*t,507+25*Math.sin(t*Math.PI),0.15+0.7*Math.sin(t*Math.PI)],22),2);
  await S.skipTo('damp',{points:[[415,347],[550,460]]});
  log('lift one soft light, then let the paint set');
  S.tool('lift'); h.setBrushPreset('round'); V.dipLoad=0; V.brushRadius=21;
  await S.path(curve(t=>[390+19*Math.sin(t*Math.PI),305+64*t,0.2+0.4*Math.sin(t*Math.PI)],12),2);
  await dry();
  log('stem, cavity, and a few linen folds');
  load([['Raw Umber',2],['Perylene Violet',1]],0.32,6,0.2);
  await S.path([[432,259,0.2],[450,269,0.7],[471,268,0.5],[485,258,0.1]],3);
  load('Raw Umber',0.6,5,0.25);
  await S.path([[457,263,0.9],[458,245,0.75],[470,222,0.35]],4);
  load([['French Ultramarine',2],['Transparent Red Oxide',1]],0.045,8,0.15);
  for(const line of [[[127,608,0.1],[252,581,0.5],[343,580,0.1]],[[660,618,0.1],[753,641,0.45],[881,631,0.1]],[[199,674,0.1],[349,643,0.3],[440,645,0.1]]]) await S.path(line,5);
  await dry();
  await S.look('finished');
  await S.note('Sol, imagined red apple on linen. Warm pale background, violet cast shadow brushed into a wider damp oval, variegated red body, thirsty curved shadow strokes at satin, a single lifted light at damp. No physics changes.');
  log('done');
})();
